/// <summary>
/// This file implements the SemanticKernelLoggerBridge. It operates as an architectural adapter,
/// intercepting standardized telemetry streams from the Microsoft.Extensions.Logging framework 
/// employed by Semantic Kernel, and translating them into bounded routing formats compatible with 
/// the generalized CrypTool 2 host logging infrastructure.
/// </summary>

using CrypTool.CrypLLM.Properties;
using Microsoft.Extensions.Logging;
using System;

namespace CrypTool.CrypLLM.Services
{
    /// <summary>
    /// Encapsulates bridging heuristics to channel Semantic Kernel telemetry.
    /// Addresses system noise attenuation by explicitly filtering high-frequency, low-value diagnostic events
    /// before they permeate into the user interface log view.
    /// </summary>
    internal static class SemanticKernelLoggerBridge
    {
        /// <summary>
        /// Instantiates a custom dependency-injectable logging provider necessary for Semantic Kernel instantiation.
        /// </summary>
        public static ILoggerProvider CreateProvider()
        {
            return new CrypLlmSemanticKernelLoggerProvider();
        }

        /// <summary>
        /// Reads the persistence-layer configuration setting to enforce dynamic semantic-level gating.
        /// Isolates the LLM logging volumes from standard operational logs during non-debug phases.
        /// </summary>
        /// <returns>A mapped Microsoft.Extensions.Logging <see cref="LogLevel"/> scalar.</returns>
        public static LogLevel GetMinimumLevelFromSettings()
        {
            string raw = (Settings.Default.llmLogLevel ?? "info").Trim();
            if (raw.Equals("debug", StringComparison.OrdinalIgnoreCase))
            {
                return LogLevel.Debug;
            }

            if (raw.Equals("warning", StringComparison.OrdinalIgnoreCase))
            {
                return LogLevel.Warning;
            }

            if (raw.Equals("error", StringComparison.OrdinalIgnoreCase))
            {
                return LogLevel.Error;
            }

            return LogLevel.Information;
        }

        private sealed class CrypLlmSemanticKernelLoggerProvider : ILoggerProvider
        {
            public ILogger CreateLogger(string categoryName)
            {
                return new CrypLlmSemanticKernelLogger(categoryName ?? string.Empty);
            }

            public void Dispose()
            {
            }
        }

        /// <summary>
        /// Context-specific logger instance correlating to discrete systemic namespaces triggered by Semantic Kernel APIs.
        /// Implements targeted suppression strategies intercepting conversational noise inherently generated by verbose orchestrator models.
        /// </summary>
        private sealed class CrypLlmSemanticKernelLogger : ILogger
        {
            private readonly string _categoryName;

            public CrypLlmSemanticKernelLogger(string categoryName)
            {
                _categoryName = categoryName ?? string.Empty;
            }

            public IDisposable BeginScope<TState>(TState state)
            {
                return NoopScope.Instance;
            }

            /// <summary>
            /// Assesses whether the execution runtime permits processing for this namespace severity threshold.
            /// Early short-circuiting conserves computational overhead prior to expensive string interpolations.
            /// </summary>
            public bool IsEnabled(LogLevel logLevel)
            {
                return logLevel != LogLevel.None &&
                       logLevel >= GetMinimumLevelFromSettings() &&
                       IsRelevantCategory(_categoryName);
            }

            /// <summary>
            /// Formal intercept and translation sink for inbound telemetry formatting.
            /// Formats exceptional occurrences and injects suppression conditions to mask trivial iterative routines.
            /// </summary>
            public void Log<TState>(
                LogLevel logLevel,
                EventId eventId,
                TState state,
                Exception exception,
                Func<TState, Exception, string> formatter)
            {
                if (!IsEnabled(logLevel))
                {
                    return;
                }

                string message = formatter != null ? formatter(state, exception) : state?.ToString();
                if (string.IsNullOrWhiteSpace(message) && exception == null)
                {
                    return;
                }

                if (exception != null)
                {
                    string exceptionPart = $"{exception.GetType().Name}: {exception.Message}";
                    message = string.IsNullOrWhiteSpace(message)
                        ? exceptionPart
                        : $"{message} | {exceptionPart}";
                }

                // KernelFunction info traces ("invoking/succeeded/completed") are very noisy.
                // We render concise tool-call info in chat UI instead.
                if (string.Equals(_categoryName, "Microsoft.SemanticKernel.KernelFunction", StringComparison.OrdinalIgnoreCase) &&
                    logLevel <= LogLevel.Information)
                {
                    return;
                }

                // "Function calls: <plugin>-<function> [Id: ...]" is useful for backend diagnostics
                // but should not leak into user-facing chat traces.
                if (string.Equals(_categoryName, "Microsoft.SemanticKernel.Connectors.OpenAI.OpenAIChatCompletionService", StringComparison.OrdinalIgnoreCase) &&
                    logLevel <= LogLevel.Debug &&
                    message.IndexOf("Function calls:", StringComparison.OrdinalIgnoreCase) >= 0)
                {
                    return;
                }

                string prefixed = $"[SK][{logLevel}][{_categoryName}] {message}";

                switch (logLevel)
                {
                    case LogLevel.Critical:
                    case LogLevel.Error:
                        CrypTool.CrypLLM.Log.Error(prefixed);
                        break;
                    case LogLevel.Warning:
                        CrypTool.CrypLLM.Log.Warning(prefixed);
                        break;
                    case LogLevel.Information:
                        CrypTool.CrypLLM.Log.Info(prefixed);
                        break;
                    default:
                        CrypTool.CrypLLM.Log.Debug(prefixed);
                        break;
                }
            }
        }

        /// <summary>
        /// Validates inbound framework namespaces restricting proxy passthrough strictly to designated AI integration structures.
        /// Discards auxiliary infrastructure components mitigating unnecessary architectural coupling.
        /// </summary>
        private static bool IsRelevantCategory(string categoryName)
        {
            if (string.IsNullOrWhiteSpace(categoryName))
            {
                return false;
            }

            return categoryName.StartsWith("Microsoft.SemanticKernel", StringComparison.OrdinalIgnoreCase) ||
                   categoryName.StartsWith("Microsoft.Extensions.AI", StringComparison.OrdinalIgnoreCase) ||
                   categoryName.StartsWith("OpenAI", StringComparison.OrdinalIgnoreCase);
        }

        private sealed class NoopScope : IDisposable
        {
            public static readonly NoopScope Instance = new NoopScope();

            public void Dispose()
            {
            }
        }
    }
}
